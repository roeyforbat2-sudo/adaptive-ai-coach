@pytest.mark.parametrize(
    ("sql", "expected"),
    [
        ("SELECT * FROM t WHERE a = ? AND b = ?", "SELECT * FROM t WHERE a = %s AND b = %s"),
        ("VALUES (:source, :now)", "VALUES (%(source)s, %(now)s)"),
        ("WHERE source_id LIKE 'checkin-%'", "WHERE source_id LIKE 'checkin-%%'"),
        ("WHERE x = 'a?b' AND y = ?", "WHERE x = 'a?b' AND y = %s"),
        ("SELECT v::text, :p", "SELECT v::text, %(p)s"),
    ],
)
def test_translate_sql(sql: str, expected: str) -> None:
    assert translate_sql(sql) == expected


def test_translate_ddl_covers_every_migration() -> None:
    for m in discover():
        out = translate_ddl(m.sql)
        for sqlite_only in ("STRICT", "json_valid", "NOCASE", "RAISE(ABORT", " REAL", "INTEGER"):
            assert sqlite_only not in out, (m.name, sqlite_only)
    first = translate_ddl(discover()[0].sql)
    assert first.count("GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY") == 8
    assert "BIGINT PRIMARY KEY CHECK (id = 1)" in first  # athlete_profile keeps a fixed id
    assert "CREATE UNIQUE INDEX uq_exercises_name_ci ON exercises (lower(name))" in first
    assert "BEFORE DELETE ON audit_log FOR EACH ROW EXECUTE FUNCTION" in first


def test_row_behaves_like_sqlite_row() -> None:
    r = Row(["id", "name"], [3, "x"])
    assert r[0] == 3 and r["name"] == "x" and r.keys() == ["id", "name"]
    assert tuple(r) == (3, "x") and r == (3, "x") and len(r) == 2


def test_target_helpers(tmp_path: Path) -> None:
    db = tmp_path / "c.sqlite"
    assert is_url(URL) and not is_url(str(db))
    assert as_target(URL) == URL and as_target(str(db)) == db
    assert db_exists(URL) and not db_exists(db)
    assert describe(URL) == "Postgres (ep-x.eu-central-1.aws.neon.tech)"
    assert "s3cret" not in describe(URL)
    assert changed_marker(URL) == 0.0
    conn = connect(db)
    migrate(conn)
    assert has_column(conn, "planned_workouts", "detail")
    assert not has_column(conn, "planned_workouts", "nope")
    conn.close()
    assert changed_marker(db) > 0


def _filled(tmp_path: Path) -> Path:
    db = tmp_path / "src.sqlite"
    conn = connect(db)
    migrate(conn)
    GoalRepository(conn).add(Goal(kind=GoalKind.RACE, description="Half marathon", priority=1))
    AuditLogRepository(conn).record("user", "test", "x")
    conn.close()
    return db


def test_copy_sqlite_to_new_database_and_refuse_second_time(tmp_path: Path) -> None:
    src = connect(_filled(tmp_path), read_only=True)
    tables = read_sqlite(src)
    src.close()
    target = connect(tmp_path / "dst.sqlite")
    counts = write(target, tables)
    assert counts["goals"] == 1 and counts["audit_log"] == 1 and counts["exercises"] == 14
    with pytest.raises(CopyError, match="already has data"):
        write(target, tables)
    # New rows continue after the copied ids.
    new_id = GoalRepository(target).add(Goal(kind=GoalKind.RACE, description="Marathon"))
    assert new_id == 2
    target.close()


def test_copy_from_a_backup_export(tmp_path: Path) -> None:
    src = connect(_filled(tmp_path), read_only=True)
    tables = read_sqlite(src)
    src.close()
    export = tmp_path / "coach-export.json"
    export.write_text(
        json.dumps(
            {"format": 1, "tables": {t: {"columns": c, "rows": r} for t, (c, r) in tables.items()}}
        ),
        encoding="utf-8",
    )
    target = connect(tmp_path / "restored.sqlite")
    assert write(target, read_export(export))["goals"] == 1
    target.close()
    export.write_text('{"format": 9}', encoding="utf-8")
    with pytest.raises(CopyError, match="unknown export format"):
        read_export(export)


def test_copy_cli_needs_a_postgres_url_from_the_environment(tmp_path: Path) -> None:
    from coach.db import copy as cli

    db = _filled(tmp_path)
    assert cli.main(["--from", str(db), "--to-env"]) == 2  # no COACH_DATABASE_URL
    assert cli.main(["--from", str(tmp_path / "missing.sqlite"), "--to-env"]) == 2
    assert cli.main(["--from", str(db), "--to", str(tmp_path / "new.sqlite")]) == 0



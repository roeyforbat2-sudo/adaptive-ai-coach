@pytest.mark.postgres
def test_postgres_schema_repositories_and_copy(pg_url: str, tmp_path: Path) -> None:
    from coach.backup import _export_postgres

    pg = connect(pg_url)
    assert migrate(pg) == [m.version for m in discover()]
    assert migrate(pg) == []
    pg.close()
    src = connect(_filled(tmp_path), read_only=True)
    tables = read_sqlite(src)
    src.close()
    pg = connect(pg_url)
    counts = write(pg, tables)
    assert counts["goals"] == 1
    assert GoalRepository(pg).add(Goal(kind=GoalKind.RACE, description="Marathon")) == 2
    with pytest.raises(Exception, match="append-only"), pg:
        pg.execute("DELETE FROM audit_log")
    pg.close()
    ro = connect(pg_url, read_only=True)
    with pytest.raises(Exception, match="read-only"):
        ro.execute(
            "INSERT INTO goals (kind, description, priority, active, created_utc) "
            "VALUES ('race', 'x', 1, 1, 'now')"
        )
    ro.close()
    counts = _export_postgres(pg_url, tmp_path / "export.json")
    assert counts["goals"] == 2 and counts["audit_log"] == 1


@pytest.mark.postgres
def test_postgres_dashboard_loads_real_shaped_data(pg_url: str, tmp_path: Path) -> None:
    from datetime import date
    from zoneinfo import ZoneInfo

    from coach.services.checkin import CheckIn, save
    from coach.services.dashboard import build_view, load_dashboard_data
    from coach.synthetic import generate, seed_database

    tz = ZoneInfo("Asia/Jerusalem")
    pg = connect(pg_url)
    migrate(pg)
    seed_database(pg, generate(21, end_date=date(2026, 11, 16), seed=2, tz=tz))
    pg.close()
    save(pg_url, CheckIn(date(2026, 11, 16), rpe=6, soreness=2, fatigue=3, pain=None, ill=False))
    data = load_dashboard_data(pg_url, tz, date(2026, 11, 16))  # read-only session
    assert not data.activities.empty and not data.wellness.empty
    assert len(data.feedback) >= 1 and data.is_demo
    view = build_view(data, 4)
    assert view.overview.run_km.last_7d is not None
